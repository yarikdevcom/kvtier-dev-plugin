FOREIGN_OWNER_PREFIX = "__kvtier_dev_"

# The four verdicts the boot line and every payload carry. A closed vocabulary is the
# point: `MAMBA_ANCHOR[disabled]` and `MAMBA_ANCHOR[env-refused]` and the absence of
# the token are THREE different facts, and the whole reason the token exists is that a
# boot that patched nothing used to be indistinguishable from one that patched.
VERDICT_PATCHED = "patched"
VERDICT_REFUSED = "refused"
VERDICT_DISABLED = "disabled"
VERDICT_ENV_REFUSED = "env-refused"
VERDICTS = (VERDICT_PATCHED, VERDICT_REFUSED, VERDICT_DISABLED,
            VERDICT_ENV_REFUSED)

MAX_STRING_CHARS = 240
MAX_NOTICES = 32


def _initial_state() -> dict:
    """THE fresh-boot state, in one literal, shared by `_state` and the test reset.

    ONE BUILDER, not two copies: `backport.py`'s reset warns that a hand-copied field
    list silently stops covering new fields, and a leaked `mamba_patch_installed: True`
    is exactly the leak that would make a refusal test pass for the wrong reason.
    """
    return {
        # THE BOOT VERDICT. `verdict` is the token's value and `reason` the
        # sentence behind it; `attempted` says a decision was actually made here,
        # which is what separates `disabled` ("nothing decided yet") from
        # `refused` ("decided, and no").
        "verdict": VERDICT_DISABLED,
        "reason": None,
        "attempted": False,
        "installed": False,
        "class": None,
        "installs": 0,
        "reinstalls": 0,
        "refusals": 0,
        "skip_reason": None,
        "notice_keys": [],
        "env": None,
        "method_verdicts": {},
        "live_sha256": None,
        "expected_sha256": None,
        # THE COUNTERS. `mamba_patch_installed` is the boot-level fact the operator
        # reads beside the boot line; `anchor_offers_total` counts the marks the
        # patch actually made (see `counters()` for what the number does and does
        # not claim); `mask_*`/`fallbacks` describe the wrapper's own path.
        "mamba_patch_installed": False,
        "anchor_offers_total": 0,
        "mask_calls": 0,
        "mask_none": 0,
        "mask_empty": 0,
        "mask_already_anchored": 0,
        "fallbacks": 0,
        "last_error": None,
    }


_state: dict = _initial_state()


def reset_state_for_tests() -> None:
    """Process-wide state, like `backport._state` and `snapshot._state`. Rebuilds from
    the module's ONE `_initial_state()` builder, so a field added there is reset here
    automatically and a leaked `mamba_patch_installed: True` cannot make a later
    test's refusal assertion pass for the wrong reason.
    """
    _state.clear()
    _state.update(_initial_state())


# --- resolving the fork's names without importing it ------------------------

def mamba_manager_class():
    """`MambaManager` if this process already imported it. Never imports.

    `general_plugins` loads in worker and arg-parsing processes too, and importing
    the fork's cache-manager module from here would be a heavy side effect this
    plugin does not own - the same rule and the same reason as
    `backport.manager_class()`. In the EngineCore process the module IS there before
    the boot runs (`vllm/v1/engine/core.py:60` imports it at module scope), which is
    what makes an install at connector creation possible at all.
    """
    module = sys.modules.get(TARGET_MODULE)
    if module is None:
        return None
    return getattr(module, TARGET_CLASS, None)


# --- fingerprinting ---------------------------------------------------------

def fingerprint_of(fn) -> str | None:
    """sha256 of `inspect.getsource(fn)`, or None when there is no source."""
    try:
        return hashlib.sha256(inspect.getsource(fn).encode()).hexdigest()
    except Exception as exc:  # noqa: BLE001 - no source is a refusal, not a crash
        _state["fallbacks"] += 1
        snapshot._error(exc, "mamba_anchor fingerprint")
        return None


def _function_of(raw):
    """The plain function behind a (possibly wrapped) class-dict entry."""
    fn = raw
    while isinstance(fn, (classmethod, staticmethod)):
        fn = fn.__func__
    return fn


def _underlying(cls, name):
    """The class's OWN entry for `name`, unwrapped. (fn, is_classmethod)."""
    raw = cls.__dict__.get(name, None)
    if raw is None:
        return None, False
    return _function_of(raw), isinstance(raw, classmethod)


# --- the wrapper ------------------------------------------------------------

def _make_mask_wrapper(original):
    """The fork's own `reachable_block_mask`, then one mark on the run's end block.

    THREE RULES, in this order:

    1. THE FORK'S BODY RUNS FIRST AND ITS EXCEPTIONS TRAVEL. This is a
       pure-classmethod wrapper on the scheduler's cache path: if the fork's own body
       raises, that is the fork's story and it propagates verbatim, exactly as
       `_make_create_connector_hook` refuses to swallow the factory's ValueErrors.
       Swallowing it would hide an engine crash behind a mask.
    2. ONLY A NON-EMPTY LIST IS TOUCHED. `None` is the fork's dense verdict ("cache
       every block", the default for full attention AND the `per_segment <= 1`
       fast path for Mamba) and is returned untouched; an empty list is the fork
       saying "nothing in this range is reachable" and is likewise untouched, because
       writing `mask[-1]` into one would EXTEND the range past what the caller
       allocated a mask for.
    3. THE POST-PROCESSING IS CONTAINED. If the bookkeeping around the mark raises
       (it should not - it is a `bool` test and an assignment), the mask the FORK
       returned goes back unchanged and the event is counted as a fallback. The
       degrade direction here is "behave exactly like an unpatched boot", never
       "invent a mask", and it can never be a half-patch: the list is either the
       fork's or the fork's with its last element True.
    """
    def reachable_block_mask(cls, *args, **kwargs):
        mask = original(cls, *args, **kwargs)
        try:
            _state["mask_calls"] += 1
            if mask is None:
                _state["mask_none"] += 1
            elif isinstance(mask, list):
                if not mask:
                    _state["mask_empty"] += 1
                elif mask[-1]:
                    # The fork already anchored this run end (it landed on a segment
                    # or reachable boundary). NOT a mark: counting these would make
                    # the counter measure the fork's retention instead of the patch's
                    # contribution, which is the vacuity this counter exists to
                    # avoid.
                    _state["mask_already_anchored"] += 1
                else:
                    mask[-1] = True
                    _state["anchor_offers_total"] += 1
            else:
                # Not the declared `list[bool] | None`. Counted, and returned exactly
                # as the fork made it: a shape we do not recognise is not a shape we
                # are allowed to write into.
                _state["mask_empty"] += 1
        except Exception as exc:  # noqa: BLE001 - never break the cache path
            _state["fallbacks"] += 1
            _state["last_error"] = f"{type(exc).__name__}"[:64]
            snapshot._error(exc, "mamba_anchor mask mark")
        return mask

    setattr(reachable_block_mask, OWNER_ATTR, OWNER_TAG)
    setattr(reachable_block_mask, ORIGINAL_ATTR, original)
    reachable_block_mask.__name__ = METHOD
    reachable_block_mask.__qualname__ = f"{TARGET_CLASS}.{METHOD}"
    reachable_block_mask.__doc__ = (
        "kvtier-dev-plugin: the fork's own reachable_block_mask, then "
        "`mask[-1] = True` for a non-empty mask, so a cached range's last block "
        "carries its align state into the hash -> offer -> spill pipeline and the "
        "run it ends can be anchored from NVMe.")
    return reachable_block_mask


# --- installation -----------------------------------------------------------

def _foreign_owner(raw) -> str | None:
    """A marker from ANOTHER plugin layer on this body, or None.

    Refused rather than overwritten: `__kvtier_dev_*_owner__` is this package's own
    convention, so a marker that is not ours means another layer (ours or a foreign
    plugin's) is fitted on the fork's cache-manager class, and stacking a second
    wrapper onto it without knowing which one it is is how the 2026-10-03
    "hashed our own wrapper and blamed the fork" misattribution happens.

    BOTH shapes are inspected: the class-dict entry (a `classmethod` object does NOT
    proxy `dir()` to its function, so checking only the entry would miss every marker
    a layer puts on the body it wraps) and the function underneath it.
    """
    for candidate in (raw, _function_of(raw)):
        for name in dir(candidate):
            if (name.startswith(FOREIGN_OWNER_PREFIX)
                    and name.endswith(FOREIGN_OWNER_SUFFIX)
                    and name != OWNER_ATTR):
                return name
    return None


def already_installed(cls) -> bool:
    """True when OUR layer is live on `cls` RIGHT NOW. Deliberately NOT a memo.

    See the module docstring's inconsistency (a): this is `backport.already_installed`
    's choice, not `disk_store.install()`'s remembered bool. A module reload or
    another plugin rebinding the method removes the marker and the next `install()`
    does the work again.
    """
    if cls is None:
        return False
    raw = cls.__dict__.get(METHOD)
    if raw is None:
        return False
    return getattr(_function_of(raw), OWNER_ATTR, None) == OWNER_TAG


def install(cls=None) -> dict:
    """Fit the run-end anchor wrapper on `MambaManager`. Never raises.

    The order is the one backport.py's `install()` establishes, and for the same
    reason: read the gate, find the class, look at what the CLASS CARRIES NOW, and
    only then touch it - so a stale fingerprint, a moved method and a foreign layer
    are all refusals that leave the class exactly as they found it.

    A refusal here leaves the boot in the same shape as an unpatched boot did before
    this module existed: the fork retains its own (sparser) mask, fewer run ends are
    anchorable, and nothing else about the engine is different. That is the whole
    reason this target can be attempted at all - the refusal needs no compensating
    disarm, because there is no posture for it to be unsafe against.
    """
    report = {"installed": False, "verdict": VERDICT_DISABLED, "class": None,
              "reason": None, "methods": {}, "env": None,
              "fingerprints": {}}
    try:
        gate = config.mamba_anchor_patch()
        report["env"] = gate
        _state["env"] = gate
        if not gate["enabled"]:
            report["verdict"] = VERDICT_ENV_REFUSED
            report["reason"] = (
                f"{gate['env_var']}={gate['raw']!r} disables the run-end anchor "
                f"patch: nothing is installed (reason: env-refused)")
            _note_refuse(VERDICT_ENV_REFUSED, report["reason"])
            return report
        if gate["raw"] is not None and not gate["recognised"]:
            # Still enabled (that is the default-on grammar), but the reader is told
            # his value is not an enable word either - `disk_boot_enable()`'s rule.
            _notice("unrecognised",
                    f"{gate['env_var']}={gate['raw']!r} is neither an enable nor a "
                    f"disable word; the patch stays ENABLED (the default)")
        target = cls if cls is not None else mamba_manager_class()
        if target is None:
            report["verdict"] = VERDICT_DISABLED
            report["reason"] = (f"no {TARGET_CLASS} is imported in this process "
                                f"({TARGET_MODULE} absent)")
            _state["reason"] = report["reason"]
            logger.info("kvtier-dev-plugin: run-end anchor patch NOT attempted: %s "
                        "(normal in a worker or arg-parsing process)",
                        report["reason"])
            return report
        report["class"] = getattr(target, "__name__", type(target).__name__)
        _state["class"] = report["class"]
        _state["attempted"] = True

        raw = target.__dict__.get(METHOD)
        if raw is None:
            # NOT defined on THIS class. Inherited is a refusal, not a hint: rebinding
            # an inherited method onto `MambaManager` would change the behaviour of
            # every sibling subclass that shares the base implementation.
            report["verdict"] = VERDICT_REFUSED
            report["reason"] = (f"{TARGET_CLASS}.{METHOD} is not defined on this "
                                f"class: the fork moved it, refusing to bind it here")
            return _finish_refusal(report)
        if not isinstance(raw, classmethod):
            report["verdict"] = VERDICT_REFUSED
            report["reason"] = (f"{TARGET_CLASS}.{METHOD} is a "
                                f"{type(raw).__name__}, not a classmethod: the "
                                "calling convention changed, refusing to guess")
            return _finish_refusal(report)
        foreign = _foreign_owner(raw)
        if foreign is not None:
            report["verdict"] = VERDICT_REFUSED
            report["reason"] = (f"{TARGET_CLASS}.{METHOD} carries another layer's "
                                f"ownership marker ({foreign}): refusing to stack a "
                                "second wrapper on a body we did not fit")
            return _finish_refusal(report)

        original = _function_of(raw)
        if getattr(original, OWNER_ATTR, None) == OWNER_TAG:
            # A RE-INSTALL over our own marker: re-bind the fork's original under a
            # fresh wrapper, so a reload loop can never nest masks and never double
            # count the same run end. No fingerprint is taken of OUR OWN body (the
            # misattribution backport.py:521-540 documents).
            under = getattr(original, ORIGINAL_ATTR, None)
            if under is None:
                report.update(installed=True, verdict=VERDICT_PATCHED,
                              reason="already installed (no original to rebind)")
                _adopt(report)
                return report
            original = under
            setattr(target, METHOD, classmethod(_make_mask_wrapper(original)))
            report["methods"][METHOD] = {"patched": True,
                                         "reason": "re-installed over our own marker"}
            _state["reinstalls"] += 1
            report.update(installed=True, verdict=VERDICT_PATCHED)
            _adopt(report)
            return report

        live = fingerprint_of(original)
        expected = ORIG_SHA256[METHOD]
        report["fingerprints"][METHOD] = {"live_sha256": live,
                                          "expected_sha256": expected,
                                          "source": FINGERPRINT_SOURCE}
        _state["live_sha256"] = live
        _state["expected_sha256"] = expected
        if live is None:
            report["verdict"] = VERDICT_REFUSED
            report["reason"] = (f"{METHOD}: the live body has no readable source, so "
                                "its fingerprint is unknowable and patching blind is "
                                "the guess this guard exists to refuse")
            return _finish_refusal(report)
        if live != expected:
            report["verdict"] = VERDICT_REFUSED
            report["reason"] = (f"{METHOD}: the live body is {live}, not the "
                                f"authoring-time fingerprint {expected} "
                                f"(from {FINGERPRINT_SOURCE}); the fork moved this "
                                "method and a three-line patch against a body that "
                                "moved is a guess, so nothing is installed")
            return _finish_refusal(report)

        setattr(target, METHOD, classmethod(_make_mask_wrapper(original)))
        report["methods"][METHOD] = {"patched": True, "reason": "wrapped"}
        report.update(installed=True, verdict=VERDICT_PATCHED)
        _adopt(report)
        return report
    except Exception as exc:  # noqa: BLE001 - a plugin must not break a boot
        # `BaseException` (KeyboardInterrupt, SystemExit, CancelledError) always
        # propagates: this is the repo-wide rule, and an install that ate a
        # cancellation is how a shutdown stops being a shutdown.
        _state["fallbacks"] += 1
        _state["last_error"] = f"{type(exc).__name__}: {exc}"[:MAX_STRING_CHARS]
        snapshot._error(exc, "mamba_anchor install")
        report["installed"] = False
        report["verdict"] = VERDICT_REFUSED
        report["reason"] = f"install raised: {_state['last_error']}"
        _note_refuse(VERDICT_REFUSED, report["reason"])
        return report


def _adopt(report: dict) -> None:
    """The success bookkeeping: one loud line, once, and the boot-level fact."""
    first = not _state["mamba_patch_installed"]
    _state["installed"] = True
    _state["mamba_patch_installed"] = True
    _state["verdict"] = VERDICT_PATCHED
    _state["reason"] = None
    _state["skip_reason"] = None
    _state["method_verdicts"] = dict(report["methods"])
    if first:
        _state["installs"] += 1
        logger.warning(
            "kvtier-dev-plugin: run-end ANCHOR PATCH INSTALLED on %s.%s "
            "(fingerprint %s, source %s): a cached range's last block now carries "
            "its align state", report["class"], METHOD,
            (_state["expected_sha256"] or "?")[:12], FINGERPRINT_SOURCE)
    else:
        logger.info("kvtier-dev-plugin: run-end anchor patch re-fitted on %s.%s",
                    report["class"], METHOD)


def _finish_refusal(report: dict) -> dict:
    """The one place a refusal is recorded, so the log stays one line per episode."""
    _note_refuse(report["verdict"], report["reason"])
    return report


def _note_refuse(kind: str, reason) -> None:
    """A refusal is a boot fact: counted, published, and logged once per episode.

    The reason lands in `_state` as well as in the caller's report: the report is one
    caller's copy, while `verdict`/`reason` in the payload have to describe the BOOT
    after the install that decided it has returned.
    """
    _state["refusals"] += 1
    _state["verdict"] = kind
    _state["reason"] = (str(reason) or "")[:MAX_STRING_CHARS]
    _state["installed"] = False
    _state["mamba_patch_installed"] = False
    _state["method_verdicts"] = {}
    _notice(kind, f"run-end anchor patch NOT installed: "
                 f"{_state['reason']}")


def _notice(key: str, message: str) -> bool:
    """One log line per episode per process, the `disk_restore.notice_once` idiom.

    The snapshot polls `section()` every few seconds and the boot may retry, so a
    refusal that logged per call would be a refusal nobody reads.
    """
    try:
        if key in _state["notice_keys"]:
            return False
        _state["notice_keys"].append(key)
        del _state["notice_keys"][-MAX_NOTICES:]
        logger.warning("kvtier-dev-plugin: %s", message)
        return True
    except Exception:  # noqa: BLE001, S110 - a log line never breaks a boot
        return False


def ensure_installed() -> dict:
    """Retry the install against the class this process has NOW. Never raises.

    The boot runs it once at connector creation; this is the door the `/tier` verb
    and any later contact use, for the one case the hook cannot cover - a process
    where `MambaManager` was not imported yet at that moment. It re-reads the class
    rather than trusting `_state`, per inconsistency (a)'s choice above.
    """
    if already_installed(mamba_manager_class()):
        return {"installed": True, "verdict": VERDICT_PATCHED, "reason": None,
                "class": _state["class"], "methods": {}, "env": _state["env"],
                "fingerprints": {}}
    return install()


# --- the counters -----------------------------------------------------------

def is_installed() -> bool:
    """Is THIS process patched? The cheap read a counter gate needs.

    Reads `_state`, never the class: this is called on the offer path (via
    `disk_restore`) where the question is "did the boot that made this process fit
    the anchor patch", not "re-verify the marker 40,000 times an hour". `install()`
    is the only writer of the flag, and `already_installed()` is the door that keeps
    the flag honest across a reload.
    """
    return bool(_state["mamba_patch_installed"])


def counters() -> dict:
    """A copy of the counters for a payload. Units live in `UNITS`.

    WHAT `anchor_offers_total` CLAIMS, precisely, and what it does not. It counts the
    marks the patch MADE: each one is a run-end block that the fork would have left
    unpublished and now carries its align state into the hash -> offer -> spill
    pipeline. That is exactly "how many run-end blocks were additionally offered",
    counted at the one site where the causal event is observable. It is NOT the
    number that reached NVMe (that is `disk_store`'s `anchor_spills_completed`) and
    NOT a count of runs made anchorable (a mark only pays off if the positional
    groups cover the run too, which is `disk_restore`'s `no_boundary_anchor`
    question). A mask that already ended True is NOT counted - counting the fork's
    own boundaries as our contribution is the vacuity this distinction exists to
    prevent.
    """
    return dict(_state)


UNITS = {
    "mamba_patch_installed": "bool: is THIS process's `MambaManager` patched (the "
                             "boot fact behind the MAMBA_ANCHOR token); a worker "
                             "answers False because the mask runs in the scheduler",
    "anchor_offers_total": "run-end blocks THIS process additionally marked "
                           "reachable (unit: blocks): one per cached range whose last "
                           "block the fork left False. Not bytes, not spills, not "
                           "anchors that survived to NVMe",
    "mask_calls": "calls through the wrapper (unit: calls): the denominator for "
                  "every mask_* field below",
    "mask_none": "calls that returned the fork's dense verdict (unit: calls): "
                 "nothing to mark, and nothing marked",
    "mask_empty": "calls that returned an empty or unrecognised mask (unit: calls): "
                  "refused to write into it, counted",
    "mask_already_anchored": "calls whose last block the FORK already marked True "
                             "(unit: calls): a run end the patch did not add, which "
                             "is why it is not in `anchor_offers_total`",
    "fallbacks": "times the wrapper's own bookkeeping raised and the fork's mask was "
                 "returned unchanged (unit: internal exceptions): must stay 0",
    "installs": "the one line logged (unit: boots in this process that fitted it)",
    "reinstalls": "re-fits over our own marker (unit: reloads): nesting would double "
                  "count, so a re-fit rebinds the fork's original instead",
    "refusals": "install attempts refused (unit: attempts), each one published with "
                "its reason in `reason` and `verdict`",
}


def section() -> dict:
    """This target's own verdict and counters, with the same keys every path.

    Safe on a polled path: it reads `_state` and nothing else - no file, no engine
    object, no `sys.modules` walk.
    """
    return {"target": f"{TARGET_MODULE}.{TARGET_CLASS}.{METHOD}",
            "verdict": _state["verdict"],
            "installed": bool(_state["mamba_patch_installed"]),
            "attempted": bool(_state["attempted"]),
            "reason": _state["reason"],
            "class": _state["class"],
            "env": _state["env"],
            "fingerprints": {"expected_sha256": _state["expected_sha256"],
                             "live_sha256": _state["live_sha256"],
                             "source": FINGERPRINT_SOURCE},
            "verdicts": list(VERDICTS),
            "counters": counters(),
            "units": dict(UNITS),
            "last_error": _state["last_error"],
            "note": ("spill-side only: this patch can add data to the store and has "
                     "no door to an arm, a posture or a request path. Two suites pin "
                     "that claim about this module: the AST-pinned serve-switch file "
                     "and this target's own test file")}


def boot_token() -> str:
    """The BOOT line's token: `MAMBA_ANCHOR[patched|refused|disabled|env-refused]`.

    Bracketed, not `key=value`, for two reasons: the verdict is a CLOSED vocabulary
    rather than a field an operator might want to compare, and the restart verifier
    in the llm-api repo extracts the tier verdict with
    `grep -oE "tier=[A-Za-z_]+" | tail -1` - a field named `mamba_anchor=` would be
    invisible to that grep either way, but a token with no `=` cannot become a
    candidate `tier=` match by accident, and the boot line's "every field name
    appears exactly once" rule (tests/test_auto_boot.py) is about `=`-shaped fields.
    """
    verdict = _state["verdict"]
    if verdict not in VERDICTS:
        verdict = VERDICT_REFUSED
    return f"MAMBA_ANCHOR[{verdict}]"
